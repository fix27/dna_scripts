/**
 * Implements a 32-bit CRC check following the general, slice-by-eight
 * method outlined in
 * ftp://download.intel.com/technology/comms/perfnet/download/slicing-by-8.pdf
 * and
 * http://www.intel.com/technology/comms/perfnet/download/crc_generators.pdf
 *
 * @param m_buf Pointer to a character array for which we would like to calculate the CRC
 * @param m_size Number of bytes to use from #buf for the CRC
 * @param m_seed Seed value to use for CRC
 * @return Computed CRC value.  This function can not fail.
 */
uint32_t
fqpack_crc32(const uint8_t *m_buf, size_t m_size, uint32_t m_seed)
{
	register uint32_t seed_val = ~m_seed;
	uint32_t remainder_size = m_size;

	if (m_size > 8)
	{
		while ((uintptr_t) (m_buf) & 0b111)
		{
			seed_val = fqpack_crc32_table[0][*m_buf++ ^ LOW_BYTE(seed_val)] ^ (seed_val>>8);
			--m_size;
		}

		const uint8_t * const stop_pos = m_buf + (m_size & ~(size_t) (7));
		remainder_size = m_size & 0b111;

		while (m_buf < stop_pos)
		{
			seed_val ^= *(const uint32_t *) (m_buf);
			m_buf += 4;

			seed_val = 	fqpack_crc32_table[7][LOW_BYTE(seed_val)] ^
						fqpack_crc32_table[6][MID_LOW_BYTE(seed_val)] ^
						fqpack_crc32_table[5][MID_HIGH_BYTE(seed_val)] ^
						fqpack_crc32_table[4][HIGH_BYTE(seed_val)];

			const uint32_t tmp = *(const uint32_t *) (m_buf);
			m_buf += 4;

			seed_val = 	fqpack_crc32_table[3][LOW_BYTE(tmp)] ^
						fqpack_crc32_table[2][MID_LOW_BYTE(tmp)] ^
						seed_val ^
						fqpack_crc32_table[1][MID_HIGH_BYTE(tmp)]	^
						fqpack_crc32_table[0][HIGH_BYTE(tmp)];
		}
	}

	while (remainder_size--)
		seed_val = fqpack_crc32_table[0][*m_buf++ ^ LOW_BYTE(seed_val)] ^ (seed_val>>8);

	return ~seed_val;
}
